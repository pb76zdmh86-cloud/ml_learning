import pandas as pd
df=pd.read_csv("apartments_review.csv")
print(df)
print(df.shape)
print(df.isna().sum())
print(df.duplicated().sum())
clean=df.drop_duplicates()
clean=clean.dropna(subset=["price"]).copy()
median_area=clean["area"].median()
clean["area"]=clean["area"].fillna(median_area)
print(clean)
print(median_area)
print(clean.shape)
print(clean.isna().sum())
print(clean.duplicated().sum())
clean.to_csv("apartments_review_clean.csv",index=False)
